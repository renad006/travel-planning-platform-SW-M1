import PDFDocument from 'pdfkit';

interface PdfActivity {
  name: string;
  description?: string;
  time?: string;
  cost?: number;
  currency?: string;
}

interface PdfBudgetEntry {
  category: string;
  amount: number;
  currency: string;
  bookingType?: string;
}

interface PdfTransportCost {
  mode: string;
  fromCity: string;
  toCity: string;
  amount: number;
  currency: string;
}

interface PdfGroupSubtotal {
  total: Record<string, number>;
  byCategory: Record<string, Record<string, number>>;
}

interface PdfDay {
  dayNumber: number;
  city: string;
  notes?: string;
  date: string;
  activities: PdfActivity[];
  budgetEntries: PdfBudgetEntry[];
  transportCosts: PdfTransportCost[];
  groupBudgetSubtotal?: PdfGroupSubtotal;
}

export interface ItineraryPdfView {
  id: string;
  title: string;
  countries: string[];
  startDate: string | Date;
  daysCount: number;
  days: PdfDay[];
}

/** "123.45 USD, 80.00 EUR" from a currency-keyed amount map; "" if empty. */
function formatAmountMap(amounts: Record<string, number>): string {
  return Object.entries(amounts)
    .map(([currency, amount]) => `${amount.toFixed(2)} ${currency}`)
    .join(', ');
}

/**
 * ITN-28 (Bonus): the downloadable itinerary. Returns a PDFKit document; the
 * caller pipes it to the response and calls `end()` (same pattern as FLT-23's e-ticket).
 */
export function renderItineraryPdf(
  itinerary: ItineraryPdfView,
): PDFKit.PDFDocument {
  const doc = new PDFDocument({
    size: 'A4',
    margin: 50,
    info: {
      Title: `Itinerary - ${itinerary.title}`,
      Author: 'Travel Planning and Booking Platform',
    },
  });

  doc.fontSize(24).font('Helvetica-Bold').text(itinerary.title);
  doc.moveDown(0.2).fontSize(10).font('Helvetica').fillColor('#555555');
  doc.text('Travel Planning and Booking Platform');
  doc.fillColor('#000000').moveDown(1);

  doc
    .fontSize(12)
    .font('Helvetica-Bold')
    .text(`Countries: ${itinerary.countries.join(', ') || '-'}`);
  doc
    .font('Helvetica')
    .text(
      `Start date: ${new Date(itinerary.startDate).toISOString().slice(0, 10)}`,
    );
  doc.text(`Duration: ${itinerary.daysCount} day(s)`);
  doc.moveDown(1);

  for (const day of itinerary.days) {
    doc
      .fontSize(14)
      .font('Helvetica-Bold')
      .text(`Day ${day.dayNumber} - ${day.city} (${day.date})`);
    doc.moveDown(0.3);

    if (day.notes) {
      doc
        .fontSize(10)
        .font('Helvetica-Oblique')
        .fillColor('#555555')
        .text(day.notes);
      doc.fillColor('#000000').moveDown(0.3);
    }

    if (day.activities.length) {
      doc.fontSize(11).font('Helvetica-Bold').text('Activities');
      doc.font('Helvetica');
      for (const activity of day.activities) {
        const label = [activity.time, activity.name].filter(Boolean).join(' ');
        doc.text(`  - ${label}`);
        if (activity.description) {
          doc.fontSize(9).fillColor('#555555').text(`    ${activity.description}`);
          doc.fontSize(11).fillColor('#000000');
        }
        if (typeof activity.cost === 'number') {
          doc.text(`    Cost: ${activity.cost.toFixed(2)} ${activity.currency ?? ''}`);
        }
      }
      doc.moveDown(0.3);
    }

    if (day.transportCosts.length) {
      doc.fontSize(11).font('Helvetica-Bold').text('Transport');
      doc.font('Helvetica');
      for (const t of day.transportCosts) {
        doc.text(`  - ${t.mode}: ${t.fromCity} to ${t.toCity} - ${t.amount.toFixed(2)} ${t.currency}`);
      }
      doc.moveDown(0.3);
    }

    if (day.budgetEntries.length) {
      doc.fontSize(11).font('Helvetica-Bold').text('Budget');
      doc.font('Helvetica');
      for (const entry of day.budgetEntries) {
        const linked = entry.bookingType ? ` (linked ${entry.bookingType} booking)` : '';
        doc.text(`  - ${entry.category}: ${entry.amount.toFixed(2)} ${entry.currency}${linked}`);
      }
    }

    const totalLabel = day.groupBudgetSubtotal
      ? formatAmountMap(day.groupBudgetSubtotal.total)
      : '';
    if (totalLabel) {
      doc.font('Helvetica-Bold').text(`  City group subtotal: ${totalLabel}`);
    }

    doc.moveDown(0.8);
  }

  doc.moveDown(1).fontSize(9).font('Helvetica').fillColor('#555555');
  doc.text('Generated by Travel Planning and Booking Platform.');
  return doc;
}